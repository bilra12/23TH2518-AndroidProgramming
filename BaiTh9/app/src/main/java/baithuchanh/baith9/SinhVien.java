package baithuchanh.baith9;

public class SinhVien {

    private String hoTen;
    private String lop;
    private String mssv;

    public SinhVien(String hoTen, String lop, String mssv) {
        this.hoTen = hoTen;
        this.lop = lop;
        this.mssv = mssv;
    }

    public String getHoTen() {
        return hoTen;
    }

    public String getLop() {
        return lop;
    }

    public String getMssv() {
        return mssv;
    }
}
